function emitTs(loc, exportName, table) {
  const keys = Object.keys(en);
  const lines = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(table[k] || en[k])},`);
  if (loc === "en") {
    return `/** English messages — domain: computer-use */\nexport const ${exportName} = {\n${lines.join("\n")}\n} as const;\n`;
  }
  return `/** ${loc} messages — domain: computer-use */\nexport const ${exportName} = {\n${lines.join("\n")}\n};\n`;
}

function patchIndex(loc) {
  const p = prefix[loc];
  const file = join(MSG, loc, "index.ts");
  let text = readFileSync(file, "utf8");
  const importLine = `import { ${p}ComputerUse } from "./computer-use";`;
  if (!text.includes("./computer-use")) {
    text = text.replace(
      `import { ${p}SettingsPet } from "./settings-pet";`,
      `import { ${p}SettingsPet } from "./settings-pet";\n${importLine}`,
    );
  }
  if (!text.includes(`...${p}ComputerUse`)) {
    text = text.replace(
      `  ...${p}SettingsPet,`,
      `  ...${p}SettingsPet,\n  ...${p}ComputerUse,`,
    );
  }
  writeFileSync(file, text);
}

for (const loc of Object.keys(prefix)) {
  const p = prefix[loc];
  writeFileSync(join(MSG, loc, "computer-use.ts"), emitTs(loc, `${p}ComputerUse`, tables[loc] || en));
  patchIndex(loc);
}
